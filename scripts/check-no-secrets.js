#!/usr/bin/env node
/**
 * Fails the build if a credential looks like it has been committed.
 *
 * This repo is PUBLIC, and it has already lost credentials this way once:
 * a live GST API key + secret, a long-lived OTP provider bearer token, and
 * an admin password were all committed as plain string literals and are now
 * permanently in the git history. This is the tripwire so it doesn't happen
 * a third time — it runs in CI on every push
 * (.github/workflows/secret-scan.yml) and locally via `npm run check:secrets`.
 *
 * It scans the WORKING TREE only. Purging a secret from history is a
 * separate, destructive operation (git filter-repo / BFG + force-push), and
 * the only real remedy for an already-leaked value is rotation.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SKIP_DIRS = new Set(['node_modules', '.git', '.firebase', 'build', 'dist', '.gradle', 'captures']);
const SKIP_FILES = new Set(['package-lock.json', 'check-no-secrets.js']);
// google-services.json holds the Firebase ANDROID config. Like the web
// apiKey it is a public project identifier that authorises nothing on its
// own — Firestore rules are the access control — and Google ships it in
// every Android app. It is not a secret and must not be treated as one.
const SKIP_PATHS = [
  'android/app/google-services.json',
  'android/app/src/main/assets/public',   // generated by `cap sync`, gitignored
];
const TEXT_EXT = new Set(['.js', '.mjs', '.cjs', '.ts', '.json', '.html', '.htm', '.css', '.yml', '.yaml',
                          '.md', '.txt', '.xml', '.gradle', '.properties', '.env', '.sh', '.rules']);

// Each rule matches the SHAPE of a credential. Deliberately shape-based
// rather than a list of the known-leaked values — the point is to catch the
// next one, not to re-record the last one.
const RULES = [
  { name: 'sandbox.co.in live API key/secret', re: /\b(key|secret)_live_[A-Za-z0-9]{16,}\b/ },
  { name: 'Google API key',                    re: /\bAIza[0-9A-Za-z_-]{35}\b/ },
  { name: 'GCP service-account private key',   re: /-----BEGIN (RSA |EC )?PRIVATE KEY-----/ },
  { name: 'service-account JSON private_key',  re: /"private_key"\s*:\s*"-----BEGIN/ },
  { name: 'AWS access key id',                 re: /\bAKIA[0-9A-Z]{16}\b/ },
  { name: 'Slack token',                       re: /\bxox[abprs]-[0-9A-Za-z-]{10,}/ },
  { name: 'GitHub token',                      re: /\bgh[pousr]_[A-Za-z0-9]{36,}\b/ },
  { name: 'Stripe secret key',                 re: /\bsk_(live|test)_[A-Za-z0-9]{16,}\b/ },
  { name: 'Razorpay key',                      re: /\brzp_(live|test)_[A-Za-z0-9]{10,}\b/ },
  { name: 'Twilio account SID',                re: /\bAC[0-9a-f]{32}\b/ },
  // A fully signed JWT (three segments). Two-segment examples in docs are ignored.
  { name: 'hardcoded JWT',                     re: /\beyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{20,}/ },
  // A literal assigned to something named like a credential. The captured
  // value is then run through looksLikeSecret() below, so an identifier such
  // as `gst_api_secret: 'gst-api-secret'` (a Secret Manager *name*, not a
  // value) or a sentinel like `accessToken: 'firebase'` doesn't trip it.
  { name: 'assigned credential literal',
    re: /(password|passwd|api[_-]?secret|client[_-]?secret|auth[_-]?token|access[_-]?token|private[_-]?key)\s*[:=]\s*['"]([^'"\s]{8,})['"]/i,
    valueGroup: 2 },
];

// Real credentials are long and high-entropy. These are the shapes that are
// definitively NOT one, however credential-ish the variable name is.
function looksLikeSecret(v) {
  if (!v || v.length < 12) return false;
  if (/^[a-z][a-z0-9]*(-[a-z0-9]+)+$/.test(v)) return false;   // kebab-case identifier
  if (/^[a-z][a-z0-9]*(_[a-z0-9]+)+$/.test(v)) return false;   // snake_case identifier
  if (/^\$?\{|\$\(/.test(v)) return false;                     // template / shell reference
  if (/^(true|false|null|undefined|demo|firebase|test|example|changeme|placeholder)$/i.test(v)) return false;
  if (/^(https?|tel|mailto):/.test(v)) return false;
  const classes = [/[a-z]/, /[A-Z]/, /[0-9]/].filter((r) => r.test(v)).length;
  return classes >= 2 || /^[0-9a-f]{24,}$/i.test(v);           // mixed case/digits, or a long hex run
}

// The Firebase Web API key is public by design — it identifies the project
// and authorises nothing (Firestore rules decide access), so the generic
// "Google API key" rule would otherwise fire on every legitimate use.
const ALLOWLIST = [
  /apiKey:\s*["']AIza[0-9A-Za-z_-]{35}["']/,          // Firebase web config
  /["']AIzaSyD-3RNHrI9ZPmdTioLiuCi2gjwdNXZH8HI["']/,  // this project's public web API key
  /PASTE_[A-Z_]+/,                                     // placeholders
  /process\.env\./, /\$\{\{\s*secrets\./,              // references, not values
  /window\.APP_SECRETS/,
  /autocomplete\s*=/, /type\s*=\s*["']password["']/,   // password INPUTS, not values
];

let findings = 0;
const NUL = String.fromCharCode(0);

function scanFile(file) {
  const rel = path.relative(ROOT, file).replace(/\\/g, '/');
  if (SKIP_PATHS.some((skip) => rel === skip || rel.startsWith(skip + '/'))) return;
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch (e) { return; }
  if (text.indexOf(NUL) !== -1) return;   // binary
  text.split(/\r?\n/).forEach((line, i) => {
    if (ALLOWLIST.some((a) => a.test(line))) return;
    for (const rule of RULES) {
      const m = line.match(rule.re);
      if (m) {
        if (rule.valueGroup && !looksLikeSecret(m[rule.valueGroup])) continue;
        // Report the location and the rule — never the matched value.
        console.error(`  ${rel}:${i + 1}  possible ${rule.name}`);
        findings++;
        break;
      }
    }
  });
}

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') && entry.name !== '.github' && entry.name !== '.env.example') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) { if (!SKIP_DIRS.has(entry.name)) walk(full); continue; }
    if (SKIP_FILES.has(entry.name)) continue;
    if (!TEXT_EXT.has(path.extname(entry.name))) continue;
    scanFile(full);
  }
}

console.log('Scanning working tree for committed credentials...');
walk(ROOT);
if (findings) {
  console.error(`\nFAILED: ${findings} possible credential(s) in the working tree.`);
  console.error('Move the value into CI secrets (see scripts/inject-secrets.js) and ROTATE it — assume it is already public.');
  process.exit(1);
}
console.log('OK: no committed credentials detected.');
